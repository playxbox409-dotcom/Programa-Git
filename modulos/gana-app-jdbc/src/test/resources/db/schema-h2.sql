DROP TABLE IF EXISTS animales;
DROP TABLE IF EXISTS usuarios;

CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    correo VARCHAR(150) NOT NULL UNIQUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE animales (
    id_animal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propietario BIGINT NOT NULL,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    especie VARCHAR(30) NOT NULL,
    raza VARCHAR(80) NOT NULL,
    fecha_nacimiento DATE,
    peso_kg DECIMAL(10, 2) NOT NULL CHECK (peso_kg > 0),
    precio_cop DECIMAL(14, 2) NOT NULL CHECK (precio_cop >= 0),
    ubicacion VARCHAR(120) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_animales_propietario FOREIGN KEY (id_propietario) REFERENCES usuarios (id_usuario)
);

